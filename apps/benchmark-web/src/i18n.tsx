DICTIONARIES.en = Object.fromEntries(Object.keys(DICTIONARIES.es).map((key) => [key, key]));

interface I18nContextValue {
  readonly language: Language;
  readonly setLanguage: (language: Language) => void;
  readonly t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

/**
 * Proveedor global de idioma con persistencia local.
 */
export function I18nProvider({ children }: { readonly children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const stored = localStorage.getItem("trace-benchmark-language");
    return stored === "en" ? "en" : "es";
  });

  function changeLanguage(nextLanguage: Language): void {
    localStorage.setItem("trace-benchmark-language", nextLanguage);
    setLanguage(nextLanguage);
  }

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage: changeLanguage,
    t: (key: string) => DICTIONARIES[language][key] ?? key,
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/**
 * Expone idioma y función de traducción a cualquier componente de UI.
 */
export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
